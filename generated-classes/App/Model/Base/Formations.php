    /**
     * Persists this object to the database.
     *
     * If the object is new, it inserts it; otherwise an update is performed.
     * All modified related objects will also be persisted in the doSave()
     * method. This method wraps all precipitate database operations in a
     * single transaction.
     *
     * @param \Propel\Runtime\Connection\ConnectionInterface|null $con
     *
     * @throws \Propel\Runtime\Exception\PropelException
     *
     * @return int The number of rows affected by this insert/update and any referring fk objects' save() operations.
     */
    public function save(?ConnectionInterface $con = null): int
    {
        if ($this->isDeleted()) {
            throw new PropelException('You cannot save an object that has been deleted.');
        }

        if ($this->alreadyInSave) {
            return 0;
        }

        if ($con === null) {
            $con = Propel::getServiceContainer()->getWriteConnection(FormationsTableMap::DATABASE_NAME);
        }

        return $con->transaction(function () use ($con) {
            $ret = $this->preSave($con);
            $isInsert = $this->isNew();
            if ($isInsert) {
                $ret = $ret && $this->preInsert($con);
            } else {
                $ret = $ret && $this->preUpdate($con);
            }
            if ($ret) {
                $affectedRows = $this->doSave($con);
                if ($isInsert) {
                    $this->postInsert($con);
                } else {
                    $this->postUpdate($con);
                }
                $this->postSave($con);
                FormationsTableMap::addInstanceToPool($this);
            } else {
                $affectedRows = 0;
            }

            return $affectedRows;
        });
    }

    /**
     * Performs the work of inserting or updating the row in the database.
     *
     * If the object is new, it inserts it; otherwise an update is performed.
     * All related objects are also updated in this method.
     *
     * @see static::save()
     *
     * @param \Propel\Runtime\Connection\ConnectionInterface $con
     *
     * @return int The number of rows affected by this insert/update and any referring fk objects' save() operations.
     */
    protected function doSave(ConnectionInterface $con): int
    {
        if ($this->alreadyInSave) {
            return 0;
        }

        $affectedRows = 0; // initialize var to track total num of affected rows
        $this->alreadyInSave = true;

        // We call the save method on the following object(s) if they
        // were passed to this object by their corresponding set
        // method. This object relates to these object(s) by a
        // foreign key reference.

        if ($this->aArmies !== null) {
            if ($this->aArmies->isModified() || $this->aArmies->isNew()) {
                $affectedRows += $this->aArmies->save($con);
            }
            $this->setArmies($this->aArmies);
        }

        if ($this->isNew() || $this->isModified()) {
            // persist changes
            if ($this->isNew()) {
                $this->doInsert($con);
                $affectedRows += 1;
            } else {
                $affectedRows += $this->doUpdate($con);
            }
            $this->resetModified();
        }

        if ($this->formationUnitssScheduledForDeletion !== null) {
            if (!$this->formationUnitssScheduledForDeletion->isEmpty()) {
                ChildFormationUnitsQuery::create()
                    ->filterByPrimaryKeys($this->formationUnitssScheduledForDeletion->getPrimaryKeys(false))
                    ->delete($con);
                $this->formationUnitssScheduledForDeletion = null;
            }
        }

        if ($this->collFormationUnitss !== null) {
            foreach ($this->collFormationUnitss as $referrerFK) {
                if (!$referrerFK->isDeleted() && ($referrerFK->isNew() || $referrerFK->isModified())) {
                    $affectedRows += $referrerFK->save($con);
                }
            }
        }

        $this->alreadyInSave = false;

        return $affectedRows;
    }

    /**
     * Insert the row in the database.
     *
     * @see static::doSave()
     *
     * @param \Propel\Runtime\Connection\ConnectionInterface $con
     *
     * @throws \RuntimeException
     * @throws \Propel\Runtime\Exception\PropelException
     *
     * @return void
     */
    protected function doInsert(ConnectionInterface $con): void
    {
        $modifiedColumns = [];
        $index = 0;
        $this->modifiedColumns[FormationsTableMap::COL_ID] = true;
        if ($this->id !== null) {
            throw new PropelException('Cannot insert a value for auto-increment primary key (' . FormationsTableMap::COL_ID . ')');
        }

         // check the columns in natural order for more readable SQL queries
        if ($this->isColumnModified(FormationsTableMap::COL_ID)) {
            $modifiedColumns[':p' . $index++] = '`id`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_ARMY_ID)) {
            $modifiedColumns[':p' . $index++] = '`army_id`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_NAME)) {
            $modifiedColumns[':p' . $index++] = '`name`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_FORMATION_TYPE)) {
            $modifiedColumns[':p' . $index++] = '`formation_type`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_PV_BUDGET)) {
            $modifiedColumns[':p' . $index++] = '`pv_budget`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_IS_ACTIVE)) {
            $modifiedColumns[':p' . $index++] = '`is_active`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_CREATED_AT)) {
            $modifiedColumns[':p' . $index++] = '`created_at`';
        }
        if ($this->isColumnModified(FormationsTableMap::COL_UPDATED_AT)) {
            $modifiedColumns[':p' . $index++] = '`updated_at`';
        }

        $sql = sprintf(
            'INSERT INTO `formations` (%s) VALUES (%s)',
            implode(', ', $modifiedColumns),
            implode(', ', array_keys($modifiedColumns)),
        );

        try {
            $stmt = $con->prepare($sql);
            if (!$stmt) {
                throw new RuntimeException("Failed to build PreparedStatement for SQL '$sql'");
            }
            foreach ($modifiedColumns as $identifier => $columnName) {
                switch ($columnName) {
                    case '`id`':
                        $stmt->bindValue($identifier, $this->id, PDO::PARAM_INT);

                        break;
                    case '`army_id`':
                        $stmt->bindValue($identifier, $this->army_id, PDO::PARAM_INT);

                        break;
                    case '`name`':
                        $stmt->bindValue($identifier, $this->name, PDO::PARAM_STR);

                        break;
                    case '`formation_type`':
                        $stmt->bindValue($identifier, $this->formation_type, PDO::PARAM_STR);

                        break;
                    case '`pv_budget`':
                        $stmt->bindValue($identifier, $this->pv_budget, PDO::PARAM_INT);

                        break;
                    case '`is_active`':
                        $stmt->bindValue($identifier, (int)$this->is_active, PDO::PARAM_INT);

                        break;
                    case '`created_at`':
                        $stmt->bindValue($identifier, $this->created_at ? $this->created_at->format('Y-m-d H:i:s.u') : null, PDO::PARAM_STR);

                        break;
                    case '`updated_at`':
                        $stmt->bindValue($identifier, $this->updated_at ? $this->updated_at->format('Y-m-d H:i:s.u') : null, PDO::PARAM_STR);

                        break;
                }
            }
            $stmt->execute();
        } catch (Exception $e) {
            Propel::log($e->getMessage(), Propel::LOG_ERR);

            throw new PropelException("Unable to execute INSERT statement [$sql]", 0, $e);
        }

        try {
            $pk = $con->lastInsertId();
        } catch (Exception $e) {
            throw new PropelException('Unable to get autoincrement id.', 0, $e);
        }
        $this->setId((int)$pk);

        $this->setNew(false);
    }

