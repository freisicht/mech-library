                foreach ($collUnitAbilitiess as $obj) {
                    if (!$this->collUnitAbilitiess->contains($obj)) {
                        $this->collUnitAbilitiess->append($obj);
                    }
                }

                $this->collUnitAbilitiessPartial = true;
            }

            return $collUnitAbilitiess;
        }

        if ($this->collUnitAbilitiessPartial && $this->collUnitAbilitiess) {
            foreach ($this->collUnitAbilitiess as $obj) {
                if ($obj->isNew()) {
                    $collUnitAbilitiess[] = $obj;
                }
            }
        }

        $this->collUnitAbilitiess = $collUnitAbilitiess;
        $this->collUnitAbilitiessPartial = false;

        return $this->collUnitAbilitiess;
    }

    /**
     * Sets a collection of units objects related by a one-to-many relationship
     * to the current object.
     *
     * It will also schedule objects for deletion based on a diff between old objects (aka persisted)
     * and new objects from the given Propel collection.
     *
     * @param \Propel\Runtime\Collection\Collection<\App\Model\UnitAbilities> $unitAbilitiess
     * @param \Propel\Runtime\Connection\ConnectionInterface|null $con
     *
     * @return static
     */
    public function setUnitAbilitiess(Collection $unitAbilitiess, ?ConnectionInterface $con = null): static
    {
        $unitAbilitiessToDelete = $this->getUnitAbilitiess(null, $con)->diff($unitAbilitiess);

        $this->unitAbilitiessScheduledForDeletion = $unitAbilitiessToDelete;

        foreach ($unitAbilitiessToDelete as $unitAbilitiesRemoved) {
            $unitAbilitiesRemoved->setUnits(null);
        }

        $this->collUnitAbilitiess = null;
        foreach ($unitAbilitiess as $unitAbilities) {
            $this->addUnitAbilities($unitAbilities);
        }

        $this->collUnitAbilitiessPartial = false;
        $this->collUnitAbilitiess = $unitAbilitiess instanceof UnitAbilitiesCollection
            ? $unitAbilitiess : new UnitAbilitiesCollection($unitAbilitiess->getData());

        return $this;
    }

    /**
     * Returns the number of related units objects.
     *
     * @param \Propel\Runtime\ActiveQuery\Criteria|null $criteria
     * @param bool $distinct
     * @param \Propel\Runtime\Connection\ConnectionInterface|null $con
     *
     * @return int Count of related units objects.
     */
    public function countUnitAbilitiess(?Criteria $criteria = null, bool $distinct = false, ?ConnectionInterface $con = null): int
    {
        $partial = $this->collUnitAbilitiessPartial && !$this->isNew();
        if ($this->collUnitAbilitiess === null || $criteria !== null || $partial) {
            if ($this->isNew() && $this->collUnitAbilitiess === null) {
                return 0;
            }

            if ($partial && !$criteria) {
                return count($this->getUnitAbilitiess());
            }

            $query = ChildUnitAbilitiesQuery::create(null, $criteria);
            if ($distinct) {
                $query->distinct();
            }

            return $query
                ->filterByUnits($this)
                ->count($con);
        }

        return count($this->collUnitAbilitiess);
    }

    /**
     * Method called to associate a ChildUnitAbilities object to this object
     * through the ChildUnitAbilities foreign key attribute.
     *
     * @param \App\Model\UnitAbilities $childUnitAbilities
     *
     * @return $this
     */
    public function addUnitAbilities(ChildUnitAbilities $childUnitAbilities)
    {
        if ($this->collUnitAbilitiess === null) {
            $this->initUnitAbilitiess();
            $this->collUnitAbilitiessPartial = true;
        }

        if (!$this->collUnitAbilitiess->contains($childUnitAbilities)) {
            $this->doAddUnitAbilities($childUnitAbilities);

            if ($this->unitAbilitiessScheduledForDeletion && $this->unitAbilitiessScheduledForDeletion->contains($childUnitAbilities)) {
                $this->unitAbilitiessScheduledForDeletion->remove($this->unitAbilitiessScheduledForDeletion->search($childUnitAbilities));
            }
        }

        return $this;
    }

    /**
     * @param \App\Model\UnitAbilities $unitAbilities The ChildUnitAbilities object to add.
     *
     * @return void
     */
    protected function doAddUnitAbilities(ChildUnitAbilities $unitAbilities): void
    {
        $this->collUnitAbilitiess->append($unitAbilities);
        assert($this instanceof ChildUnits);
        $unitAbilities->setUnits($this);
    }

    /**
     * @param \App\Model\UnitAbilities $unitAbilities The ChildUnitAbilities object to remove.
     *
     * @return static
     */
    public function removeUnitAbilities(ChildUnitAbilities $unitAbilities): static
    {
        if ($this->getUnitAbilitiess()->contains($unitAbilities)) {
            $pos = $this->collUnitAbilitiess->search($unitAbilities);
            $this->collUnitAbilitiess->remove($pos);
            if ($this->unitAbilitiessScheduledForDeletion === null) {
                $this->unitAbilitiessScheduledForDeletion = clone $this->collUnitAbilitiess;
                $this->unitAbilitiessScheduledForDeletion->clear();
            }
            $this->unitAbilitiessScheduledForDeletion->append(clone $unitAbilities);
            $unitAbilities->setUnits(null);
        }

        return $this;
    }

