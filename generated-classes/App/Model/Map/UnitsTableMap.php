    /**
     * Performs an INSERT on the database, given a Units or Criteria object.
     *
     * @param \Propel\Runtime\ActiveQuery\Criteria|\App\Model\Units $criteria
     * @param \Propel\Runtime\Connection\ConnectionInterface|null $con
     *
     * @throws \Propel\Runtime\Exception\PropelException Any exceptions caught during processing will be
     *                         rethrown wrapped into a PropelException.
     *
     * @return mixed The new primary key.
     */
    public static function doInsert($criteria, ?ConnectionInterface $con = null)
    {
        if ($con === null) {
            $con = Propel::getServiceContainer()->getWriteConnection(UnitsTableMap::DATABASE_NAME);
        }

        if ($criteria instanceof Criteria) {
            $criteria = clone $criteria;
            $criteria->turnFiltersToUpdateValues();
        } else {
            $criteria = $criteria->buildCriteria(); // build Criteria from Units object
        }

        if ($criteria->hasUpdateValue(UnitsTableMap::COL_ID)) {
            throw new PropelException('Cannot insert a value for auto-increment primary key (UnitsTableMap::COL_ID)');
        }

        // Set the correct dbName
        $query = UnitsQuery::create()->mergeWith($criteria);

        // use transaction because $criteria could contain info
        // for more than one table (I guess, conceivably)
        return $con->transaction(function () use ($con, $query) {
            return $query->doInsert($con);
        });
    }
