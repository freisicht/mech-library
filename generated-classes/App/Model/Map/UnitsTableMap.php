    /**
     * @deprecated Delete via model or UnitsQuery.
     *
     * Performs a DELETE on the database, given a Units or Criteria object OR a primary key value.
     *
     * @param mixed $values Criteria or Units object or primary key or array of primary keys
     *              which is used to create the DELETE statement
     * @param \Propel\Runtime\Connection\ConnectionInterface|null $con the connection to use
     *
     * @throws \Propel\Runtime\Exception\PropelException Any exceptions caught during processing will be
     *                         rethrown wrapped into a PropelException.
     *
     * @return int The number of affected rows (if supported by underlying database driver). This includes CASCADE-related rows
     *                         if supported by native driver or if emulated using Propel.
     */
    public static function doDelete($values, ?ConnectionInterface $con = null): int
    {
        trigger_deprecation('Propel', '2.0', 'TableMap::doDelete() should not be used anymore, delete via model or UnitsQuery');

        if ($con === null) {
            $con = Propel::getServiceContainer()->getWriteConnection(UnitsTableMap::DATABASE_NAME);
        }

        if ($values instanceof Criteria) {
            $criteria = $values;
        } elseif ($values instanceof Units) { // it's a model object
            $criteria = $values->buildPkeyCriteria();
        } else { // it's a primary key, or an array of pks
            $criteria = new Criteria(UnitsTableMap::DATABASE_NAME);
            $criteria->addAnd(UnitsTableMap::COL_ID, (array)$values, Criteria::IN);
        }

        $query = UnitsQuery::create()->mergeWith($criteria);

        if ($values instanceof Criteria) {
            UnitsTableMap::clearInstancePool();
        } elseif (!is_object($values)) { // it's a primary key, or an array of pks
            foreach ((array)$values as $singleval) {
                UnitsTableMap::removeInstanceFromPool($singleval);
            }
        }

        return $query->delete($con);
    }

